#!/usr/bin/env python3
"""
Write .claude/skills/aisss-visual-identity/tokens.json from the same colour table the PDF is built from.

Hex values, RGB, CMYK and contrast ratios are computed from `COLORS` in build_guide.py, so the skill can't drift
from the guide. The tier / site token / use text below is copied from the PDF (pages 6-9 and 14).

Run after changing a colour in build_guide.py:
    python3 branding/guide/export_skill_tokens.py
"""
from __future__ import annotations

import json
from pathlib import Path

import build_guide as g

OUT = Path(__file__).resolve().parents[2] / ".claude" / "skills" / "aisss-visual-identity" / "tokens.json"

# name: (tier, website token or None, use). Text follows the PDF.
META: dict[str, tuple[str, str | None, str]] = {
    "Ink": ("primary", "--color-ink", "Text, the logo, dark fields, and primary buttons."),
    "Paper": ("primary", "--color-paper", "Default ground. Also type and the logo when they sit on Ink."),
    "Strand": ("primary", "--color-hero-orange", "A word or a short rule. Not body text."),
    "Ink 2": ("neutral", "--color-ink-2", "Secondary headlines and the deck under a title."),
    "Muted": ("neutral", "--color-muted", "Supporting copy, captions, and metadata."),
    "Line 2": ("neutral", "--color-line-2", "Disabled labels and quiet icons. Not for sentences."),
    "Line": ("neutral", "--color-line", "Hairlines, field borders, and dividers."),
    "Paper 3": ("neutral", "--color-paper-3", "Inactive cards and topics still in production."),
    "Paper 2": ("neutral", "--color-paper-2", "Alternate bands and secondary buttons."),
    "Warm Paper": ("warm ground", None, "Video and long documents. Do not mix with Paper in one frame."),
    "Wool": ("warm ground", None, "Panels and lower thirds on a warm ground."),
    "Wheat": ("warm ground", None, "A second panel or a chart band. Not a text color."),
    "Bark": ("warm ground", None, "Captions and axes on Warm Paper, Wool, and Wheat."),
    "Clay": ("strand family", None, "Small orange labels and icons."),
    "Live": ("strand family", "--color-library-live", "Available states. Large fills only, with Ink type on top."),
    "Ember": ("strand family (state)", "--color-library-live-hover", "The Live hover. Not a headline colour."),
    "Indigo": ("signal", None, "Diagram structure and document links. One cool color, used flat."),
    "Moss": ("signal", None, "The confirmed point: a node, a tag, a correct path."),
    "Saffron": ("signal", None, "A tick or a short underline. Not a sentence."),
}

# (foreground, background, role). The pairs the PDF approves for type (page 9).
PAIRS = [
    ("Ink", "Paper", "Default body and headlines"),
    ("Ink", "Paper 2", "Secondary buttons and bands"),
    ("Ink", "Warm Paper", "Video and print body"),
    ("Ink", "Wool", "Lower thirds and panels"),
    ("Ink", "Live", "Type on an available card"),
    ("Paper", "Ink", "Reversed type and the logo"),
    ("Paper", "Indigo", "Labels on a diagram field"),
    ("Paper", "Moss", "Labels on a confirmed node"),
    ("Muted", "Paper", "Captions on the website"),
    ("Bark", "Warm Paper", "Captions on a warm ground"),
    ("Clay", "Paper", "Small Strand-family labels"),
    ("Strand", "Paper", "Emphasis at title size"),
]


def main() -> None:
    colors = []
    for name, hex_ in g.COLORS.items():
        tier, token, use = META[name]
        r, gr, b = g.rgb_of(hex_)
        c, m, y, k = g.cmyk_of(hex_)
        colors.append(
            {
                "name": name,
                "hex": hex_,
                "rgb": [r, gr, b],
                "cmyk": [c, m, y, k],
                "tier": tier,
                "siteToken": token,
                "use": use,
            }
        )
    pairs = []
    for fg, bg, role in PAIRS:
        ratio = g.contrast(g.COLORS[fg], g.COLORS[bg])
        pairs.append({"fg": fg, "bg": bg, "ratio": round(ratio, 1), "grade": g.grade(ratio), "role": role})

    data = {
        "source": "branding/AISSS-Visual-Identity.pdf (Inter edition), built by branding/guide/build_guide.py",
        "note": "Generated by branding/guide/export_skill_tokens.py. Do not edit by hand; change build_guide.py and re-run.",
        "colors": colors,
        "approvedTypePairs": pairs,
        "contrastGrades": {"AAA": ">= 7", "AA": ">= 4.5", "Large only": ">= 3 (18pt, or 14pt bold, short line)", "Do not set type": "< 3"},
        "type": {
            "sans": {"family": "Inter", "files": "branding/guide/fonts/Inter-{Regular,Medium,SemiBold,Bold}.ttf", "license": "SIL OFL", "italic": False},
            "serif": {"family": "Baskerville (Libre Baskerville as stand-in)", "files": "branding/guide/fonts/LibreBaskerville-{Regular,Bold,Italic}.ttf"},
            "hero": {"family": "Redaction 35 Regular", "file": "branding/guide/fonts/Redaction35-Regular.otf", "use": "website hero opening clause only"},
            "weights": {"400": "Body and decks", "500": "Buttons", "600": "Navigation, 12px", "700": "Wordmark and small caps"},
        },
        "logo": {
            "files": ["AISSS-logo-black.svg", "AISSS-logo-white.svg", "yarn-mark-black.svg", "yarn-mark-white.svg"],
            "location": ["motion/public/brand/", "branding/guide/logos/"],
            "clearSpace": "height of the yarn mark on every side",
            "minimum": {"lockup": "32mm / 128px wide", "mark": "8mm / 28px"},
            "webWordmark": "Inter Bold, 29px, tracking -0.055em, 3px from a 36px mark",
        },
        "graphics": {"files": ["strand-drift.svg", "strand-double.svg", "strand-corner.svg"], "location": "branding/guide/graphics/"},
        "contact": ["aisafetysaidsimply.com", "contact@aisafetysaidsimply.com"],
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(colors)} colours, {len(pairs)} pairs)")


if __name__ == "__main__":
    main()
